/**
 * Builds the single ESM artifact supplied to the Rust in-memory module loader.
 *
 * The package versions are deliberately resolved from apps/web, whose direct
 * dependency and pnpm lockfile pin memeloop@0.3.3.  This script must not fall
 * back to the registry or to an unpinned copy of the package.
 */
import { createRequire } from "node:module";
import { access, mkdir, readFile } from "node:fs/promises";
import { constants as fsConstants } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const webPackagePath = resolve(repositoryRoot, "apps/web/package.json");
const outputDirectory = resolve(repositoryRoot, "packages/agent-runtime/dist");
const outputFile = resolve(outputDirectory, "memeloop-agent-loop.bundle.mjs");
const entryPoint = resolve(
  repositoryRoot,
  "packages/agent-runtime/src/agent-loop.mjs",
);
const webRequire = createRequire(webPackagePath);

const webPackage = JSON.parse(await readFile(webPackagePath, "utf8"));
if (webPackage.dependencies?.memeloop !== "0.3.3") {
  throw new Error(
    "The embedded agent bundle requires apps/web to pin memeloop exactly at 0.3.3.",
  );
}

const loopApiCjsPath = webRequire.resolve("memeloop/loop-api");
const loopApiEsmPath = loopApiCjsPath.replace(/\.cjs$/u, ".js");
if (loopApiEsmPath === loopApiCjsPath) {
  throw new Error(`Expected an ESM sibling for ${loopApiCjsPath}.`);
}
await access(loopApiEsmPath, fsConstants.R_OK);

const memeloopPackagePath = resolve(
  dirname(loopApiEsmPath),
  "..",
  "package.json",
);
const memeloopPackage = JSON.parse(await readFile(memeloopPackagePath, "utf8"));
if (
  memeloopPackage.name !== "memeloop" ||
  memeloopPackage.version !== "0.3.3"
) {
  throw new Error(
    `Resolved ${memeloopPackage.name ?? "unknown"}@${memeloopPackage.version ?? "unknown"} instead of memeloop@0.3.3.`,
  );
}

// esbuild is Vite's locked transitive dependency in this workspace rather than
// a root dependency. Resolving from Vite preserves pnpm's isolated layout and
// avoids an unpinned package-manager lookup.
const viteRequire = createRequire(webRequire.resolve("vite"));
const esbuild = viteRequire("esbuild");
if (esbuild.version !== "0.25.12") {
  throw new Error(
    `Expected the lock-resolved esbuild@0.25.12, received esbuild@${esbuild.version}.`,
  );
}
await mkdir(outputDirectory, { recursive: true });

await esbuild.build({
  absWorkingDir: repositoryRoot,
  banner: {
    js: `/*!
 * Generated by scripts/bundle-agent.mjs from memeloop@0.3.3.
 * Project source is licensed under Apache-2.0.
 * Included upstream components retain their own licenses.
 * Third-party notices: packages/agent-runtime/THIRD_PARTY_NOTICES.md
 */`,
  },
  bundle: true,
  charset: "utf8",
  conditions: ["browser", "import", "default"],
  entryPoints: [entryPoint],
  format: "esm",
  legalComments: "inline",
  logLevel: "info",
  mainFields: ["module", "main"],
  minify: false,
  outfile: outputFile,
  platform: "neutral",
  plugins: [
    {
      name: "resolve-pinned-memeloop-loop-api",
      setup(build) {
        build.onResolve({ filter: /^memeloop\/loop-api$/ }, () => ({
          path: loopApiEsmPath,
        }));
      },
    },
  ],
  sourcemap: false,
  target: ["es2022"],
  treeShaking: true,
});
