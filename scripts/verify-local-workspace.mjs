// Finite CI check of first-party login and PostgreSQL persistence across a
// real launcher restart. Never log private state, SQL results, or Docker JSON.
import { spawn, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { lstat, readFile } from "node:fs/promises";
import { createServer } from "node:net";
import { dirname, isAbsolute, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  launcherFailureStage,
  loadState,
  verifyDockerResource,
} from "./start-local-workspace.mjs";

const repository = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const launcher = join(repository, "scripts", "start-local-workspace.mjs");
const timeoutMs = 180_000;
const dockerTimeoutMs = 30_000;
const servicePorts = [8080, 5173, 38080];
let activeLauncher;
let interrupted = false;
let stage = "prerequisites";
let launcherStage;

function assert(condition) {
  if (!condition) throw new Error("Verification failed");
}

// Match the launcher's Docker environment: no inherited DOCKER_HOST,
// DOCKER_CONTEXT, credentials, or proxy settings may redirect inspection.
function minimalEnv(extra = {}) {
  const environment = {};
  for (const key of [
    "HOME",
    "PATH",
    "Path",
    "SystemRoot",
    "WINDIR",
    "COMSPEC",
    "PATHEXT",
    "APPDATA",
    "LOCALAPPDATA",
    "USERPROFILE",
    "HOMEDRIVE",
    "HOMEPATH",
    "TMP",
    "TEMP",
  ]) {
    if (process.env[key] !== undefined) environment[key] = process.env[key];
  }
  return {
    ...environment,
    NO_PROXY: "localhost,127.0.0.1",
    no_proxy: "localhost,127.0.0.1",
    ...extra,
  };
}

function docker(args) {
  const result = spawnSync("docker", args, {
    cwd: repository,
    env: minimalEnv(),
    encoding: "utf8",
    windowsHide: true,
    timeout: dockerTimeoutMs,
    maxBuffer: 1024 * 1024,
  });
  assert(!result.error && result.status === 0);
  return result.stdout.trim();
}

function localDockerOnly() {
  const endpoint = docker([
    "context",
    "inspect",
    "--format",
    "{{.Endpoints.docker.Host}}",
  ]);
  assert(/^(unix|npipe):\/\//.test(endpoint));
  docker(["info", "--format", "{{.ServerVersion}}"]);
}

function ownedResources(config) {
  localDockerOnly();
  const [container] = JSON.parse(docker(["inspect", config.container]));
  const [volume] = JSON.parse(docker(["volume", "inspect", config.volume]));
  verifyDockerResource(config, container, "container");
  verifyDockerResource(config, volume, "volume");
  assert(container.State?.Running === true);
  assert(typeof container.Id === "string" && container.Id.length > 0);
  assert(typeof volume.CreatedAt === "string" && volume.CreatedAt.length > 0);
  assert(typeof volume.Mountpoint === "string" && volume.Mountpoint.length > 0);
  return {
    containerId: container.Id,
    volumeName: volume.Name,
    volumeCreatedAt: volume.CreatedAt,
    volumeMountpoint: volume.Mountpoint,
  };
}

function databaseSnapshot(config) {
  // The UUID is synthetically generated by loadState, not provided by an
  // external account. Only aggregate timestamps/counts leave PostgreSQL.
  assert(/^[0-9a-f-]{36}$/i.test(config.userId));
  const userId = `'${config.userId}'::uuid`;
  const sql = `SELECT (SELECT created_at::text FROM users WHERE user_id = ${userId}), count(*)::text, min(created_at)::text FROM sessions WHERE user_id = ${userId}`;
  const row = docker([
    "exec",
    config.container,
    "psql",
    "-X",
    "-A",
    "-t",
    "-F",
    "|",
    "-v",
    "ON_ERROR_STOP=1",
    "-U",
    "geo_local",
    "-d",
    "geo_local",
    "-c",
    sql,
  ]);
  const fields = row.split("|");
  assert(fields.length === 3);
  const [userCreatedAt, countText, oldestSessionAt] = fields;
  assert(userCreatedAt && oldestSessionAt && /^\d+$/.test(countText));
  const count = Number(countText);
  assert(Number.isSafeInteger(count) && count >= 1);
  return { userCreatedAt, count, oldestSessionAt };
}

async function configSnapshot(stateDir) {
  const config = await loadState(stateDir);
  const bytes = await readFile(join(stateDir, "config.json"));
  return {
    config,
    bytes,
    digest: createHash("sha256").update(bytes).digest(),
  };
}

async function assertFreePorts() {
  for (const port of servicePorts) {
    const server = createServer();
    try {
      await new Promise((done, fail) => {
        server.once("error", fail);
        server.listen({ host: "127.0.0.1", port, exclusive: true }, done);
      });
    } finally {
      if (server.listening) await new Promise((done) => server.close(done));
    }
  }
}

async function checkLauncher(environment) {
  assert(!interrupted);
  launcherStage = undefined;
  const child = spawn(process.execPath, [launcher, "--check"], {
    cwd: repository,
    env: environment,
    windowsHide: true,
    stdio: ["ignore", "ignore", "ignore", "ipc"],
  });
  child.on("message", (message) => {
    const safeStage = launcherFailureStage(message);
    if (safeStage) launcherStage = safeStage;
  });
  activeLauncher = child;
  try {
    const result = await new Promise((done) => {
      let timedOut = false;
      let grace;
      const timer = setTimeout(() => {
        timedOut = true;
        child.kill("SIGTERM");
        grace = setTimeout(() => child.kill("SIGKILL"), 15_000);
      }, timeoutMs);
      child.once("error", () => {
        clearTimeout(timer);
        clearTimeout(grace);
        done(false);
      });
      child.once("close", (code) => {
        clearTimeout(timer);
        clearTimeout(grace);
        done(!timedOut && !interrupted && code === 0);
      });
    });
    assert(result);
  } finally {
    activeLauncher = undefined;
  }
}

function handleInterrupt() {
  interrupted = true;
  activeLauncher?.kill("SIGTERM");
}

async function main() {
  assert(process.argv.length === 2);
  const binary = process.env.GEO_LOCAL_APP_BINARY;
  const stateDir = process.env.GEO_LOCAL_STATE_DIR;
  assert(binary && isAbsolute(binary));
  assert(stateDir && isAbsolute(stateDir));
  assert((await lstat(binary)).isFile());
  // The verifier must only bootstrap an unused, CI-owned ephemeral state.
  // Existing private developer state must never be used for this check.
  const preexisting = await lstat(stateDir).catch((error) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
  assert(preexisting === null);
  assert(process.env.PLAYWRIGHT_BROWSERS_PATH);
  await assertFreePorts();
  localDockerOnly();
  const environment = minimalEnv({
    GEO_LOCAL_APP_BINARY: binary,
    GEO_LOCAL_STATE_DIR: stateDir,
    PLAYWRIGHT_BROWSERS_PATH: process.env.PLAYWRIGHT_BROWSERS_PATH,
    ...(process.env.GEO_LOCAL_TMP_DIR
      ? { GEO_LOCAL_TMP_DIR: process.env.GEO_LOCAL_TMP_DIR }
      : {}),
  });

  stage = "initial launch";
  await checkLauncher(environment);
  await assertFreePorts();
  console.log("PASS first-party login and owned-service shutdown");
  stage = "initial persistent state";
  const firstConfig = await configSnapshot(stateDir);
  const firstResources = ownedResources(firstConfig.config);
  const firstDb = databaseSnapshot(firstConfig.config);
  console.log("PASS initial protected configuration and PostgreSQL session");

  stage = "restart launch";
  await checkLauncher(environment);
  await assertFreePorts();
  console.log("PASS restarted first-party login and owned-service shutdown");
  stage = "restart persistent state";
  const secondConfig = await configSnapshot(stateDir);
  const secondResources = ownedResources(secondConfig.config);
  const secondDb = databaseSnapshot(secondConfig.config);

  assert(firstConfig.bytes.equals(secondConfig.bytes));
  assert(firstConfig.digest.equals(secondConfig.digest));
  for (const key of [
    "id",
    "operatorId",
    "tenantId",
    "userId",
    "cipherKey",
    "container",
    "volume",
  ]) {
    assert(firstConfig.config[key] === secondConfig.config[key]);
  }
  assert(JSON.stringify(firstResources) === JSON.stringify(secondResources));
  assert(secondDb.count > firstDb.count);
  assert(secondDb.oldestSessionAt === firstDb.oldestSessionAt);
  assert(secondDb.userCreatedAt === firstDb.userCreatedAt);
  console.log("PASS configuration, volume, identity, and session persistence");
  console.log(
    "PASS local software/PG/cipher only; external providers and accounts unverified",
  );
}

process.on("SIGINT", handleInterrupt);
process.on("SIGTERM", handleInterrupt);
main().catch(() => {
  // Never print thrown errors: OS paths, Docker metadata, and private data
  // must not appear in CI logs. The launcher suppresses its own details too.
  console.error(
    `FAIL local workspace restart verification: ${stage}${launcherStage ? ` (${launcherStage})` : ""}`,
  );
  process.exitCode = 1;
});
