test("frozen variant hash binds revision, order and media captions before staging", () => {
  const { payload, parts } = fixture();
  assert.throws(
    () =>
      stage(payload, parts, {
        ...variantFor(payload),
        payload_hash: "b".repeat(64),
      }),
    (error) => code(error) === "rich_payload_hash_mismatch",
  );
  const frozen = variantFor(payload);
  payload.media[1].caption = "different caption";
  payload.document.blocks[1].rich.node.attrs.caption = "different caption";
  assert.throws(
    () => stage(payload, parts, frozen),
    (error) => code(error) === "rich_payload_hash_mismatch",
  );
  const other = fixture();
  other.payload.content_revision_id = BLOCK_A;
  assert.throws(
    () => stage(other.payload, other.parts, variantFor(fixture().payload)),
    (error) => code(error) === "rich_payload_hash_mismatch",
  );
});

test("denied, lost and replayed grants never call external adapter", async () => {
  for (const [authorize, expectedCode] of [
    [() => ({ status: "denied" }), "send_authorization_denied"],
    [() => ({ status: "already_consumed" }), "send_authorization_consumed"],
    [
      () => Promise.reject(new Error("secret: do not log")),
      "send_authorization_unknown",
    ],
    [
      () => ({ ...grant(), attempt_id: REVISION }),
      "send_authorization_unknown",
    ],
    [
      () => ({ ...grant(), runner_session_id: "other" }),
      "send_authorization_unknown",
    ],
    [
      () => ({ ...grant(), payload_hash: "b".repeat(64) }),
      "send_authorization_unknown",
    ],
  ]) {
    const { payload, parts } = fixture();
    const stage = stageRichPublication(payload, parts, variantFor(payload));
    let uploads = 0;
    await assert.rejects(
      executeAuthorizedRichPublication(stage, {
        expected,
        authorize,
        upload: () => uploads++,
        clock: () => Date.parse("2029-01-01T00:00:00Z"),
      }),
      (error) =>
        code(error) === expectedCode && !error.message.includes("secret"),
    );
    assert.equal(uploads, 0);
  }
});

test("expiry rechecks immediately before first external action and no replay", async () => {
  const { payload, parts } = fixture();
  const stage = stageRichPublication(payload, parts, variantFor(payload));
  let uploads = 0;
  await assert.rejects(
    executeAuthorizedRichPublication(stage, {
      expected,
      authorize: grant,
      upload: () => uploads++,
      clock: () => Date.parse("2030-01-01T00:00:00Z"),
    }),
    (error) => code(error) === "send_authorization_expired",
  );
  assert.equal(uploads, 0);
  await assert.rejects(
    executeAuthorizedRichPublication(stage, {
      expected,
      authorize: grant,
      upload: () => uploads++,
    }),
    (error) => code(error) === "rich_stage_consumed",
  );
});

