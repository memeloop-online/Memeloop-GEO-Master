test("ambiguous authorization timeout consumes the stage without upload", async () => {
  const { payload, parts } = fixture();
  const stage = stageRichPublication(payload, parts, variantFor(payload));
  let resolveAuthorization;
  const pending = new Promise((resolve) => {
    resolveAuthorization = resolve;
  });
  let uploads = 0;
  await assert.rejects(
    executeAuthorizedRichPublication(stage, {
      expected,
      authorize: () => pending,
      upload: () => uploads++,
      authorizationTimeoutMs: 5,
    }),
    (error) => code(error) === "send_authorization_unknown",
  );
  resolveAuthorization(grant());
  await Promise.resolve();
  assert.equal(uploads, 0);
  await assert.rejects(
    executeAuthorizedRichPublication(stage, {
      expected,
      authorize: grant,
      upload: () => uploads++,
    }),
    (error) => code(error) === "rich_stage_consumed",
  );
});

test("adapter ambiguity after a granted send cannot reuse stage or grant", async () => {
  const { payload, parts } = fixture();
  const frozen = stage(payload, parts);
  let authorizations = 0;
  let uploads = 0;
  await assert.rejects(
    executeAuthorizedRichPublication(frozen, {
      expected,
      authorize: () => {
        authorizations++;
        return grant();
      },
      upload: () => {
        uploads++;
        throw new Error("external outcome ambiguous");
      },
      clock: () => Date.parse("2029-01-01T00:00:00Z"),
    }),
    /external outcome ambiguous/u,
  );
  await assert.rejects(
    executeAuthorizedRichPublication(frozen, {
      expected,
      authorize: () => authorizations++,
      upload: () => uploads++,
    }),
    (error) => code(error) === "rich_stage_consumed",
  );
  assert.equal(authorizations, 1);
  assert.equal(uploads, 1);
});
